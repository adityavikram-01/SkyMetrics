"""Select 48 directions, preserving the working network and source provenance."""
import csv, json, statistics
from pathlib import Path
from prepare_dgca import CITY_CODES, prepare

HERE = Path(__file__).resolve().parent

def select_network(existing, candidates, observations, target=48):
    if target % 2: raise ValueError('Target must contain reciprocal pairs')
    pairs = {tuple(sorted(r.split('-'))) for r in candidates | existing}
    def directions(pair): return ['-'.join(pair), '-'.join(reversed(pair))]
    mandatory = {tuple(sorted(r.split('-'))) for r in existing}
    metrics = {}
    for pair in pairs:
        by_month = {}
        for row in observations:
            if row['route'] in directions(pair) and row['passengers'] is not None:
                by_month.setdefault(row['month'], {})[row['route']] = row['passengers']
        complete = {m:sum(v.values()) for m,v in by_month.items() if len(v)==2}
        metrics[pair] = {'complete_months':len(complete),
                         'mean_monthly_passengers_both_directions':statistics.mean(complete.values()) if complete else 0}
    ranked = sorted(pairs-mandatory, key=lambda p:(-metrics[p]['complete_months'],-metrics[p]['mean_monthly_passengers_both_directions'],p))
    chosen = mandatory | set(ranked[:target//2-len(mandatory)])
    if len(chosen)*2 != target: raise ValueError('Insufficient candidate pairs')
    if any(metrics[p]['complete_months']<10 for p in chosen): raise ValueError('Insufficient source coverage')
    routes = sorted(r for p in chosen for r in directions(p))
    airports = sorted({a for p in chosen for a in p})
    via = {r:[z for z in airports if z not in r.split('-') and
                 f'{r[:3]}-{z}' in routes and f'{z}-{r[4:]}' in routes] for r in routes}
    return {'directional_routes':routes, 'airports':airports,
            'pairs':[{'airports':list(p), **metrics[p], 'preserved':p in mandatory} for p in sorted(chosen)],
            'excluded_candidates':[{'airports':list(p), **metrics[p]} for p in sorted(pairs-chosen)],
            'potential_via_cities':via}

def main():
    CITY_CODES.update({'COK':'KOCHI','GAU':'GUWAHATI','LKO':'LUCKNOW','SXR':'SRINAGAR'})
    base=json.loads((HERE/'config/final-synthetic.json').read_text())
    source=Path('/Users/ujjwalsingh/Downloads')
    with (source/'sample_week_2025-10-06.csv').open() as f:
        candidates={r['route'] for r in csv.DictReader(f)}
    existing=set(base['routes'])
    calibration=prepare(source,{'routes':sorted(existing|candidates)})
    network=select_network(existing,candidates,calibration['route_months'])
    network.update(schema_version=1,is_synthetic=True,status='NETWORK_SCOPE_ONLY_NOT_GENERATED',
        selection_method='Preserve existing 24 directions; rank additional reciprocal pairs by complete source months then mean observed bidirectional monthly passenger traffic.',
        source_months='2024-01..2024-12, excluding missing May',
        limitations=['Passenger traffic does not establish nonstop airline service or exact schedules.',
          'GOA city traffic cannot distinguish GOI from GOX; retained GOI is an explicit scenario airport assignment.',
          'Via cities represent graph connectivity only; timing and separate-ticket validation still required.',
          'No schedules, fares or observations have been generated by this scope builder.'])
    out=HERE/'calibration/network-48'
    out.mkdir(parents=True,exist_ok=True)
    for name,data in [('dgca.json',calibration),('network.json',network)]:
        (out/name).write_text(json.dumps(data,indent=2)+'\n')
    print(json.dumps({'routes':len(network['directional_routes']), 'airports':len(network['airports']),
        'new_routes':sorted(set(network['directional_routes'])-existing),
        'excluded':network['excluded_candidates'],
        'routes_with_via_city':sum(bool(v) for v in network['potential_via_cities'].values()),
        'min_source_months':min(p['complete_months'] for p in network['pairs'])},indent=2))

if __name__=='__main__':main()
